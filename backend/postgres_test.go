func pgResult(t *testing.T, sqlText string, migration bool) *Result {
	t.Helper()
	cfg := defaultConfig().Rules
	return AnalyzeSQL(sqlText, "migrations/postgres/inline.sql", cfg,
		AnalyzeOptions{Migration: migration, Dialect: DialectPostgreSQL, NoUseRequired: true})
}

func TestPostgresDialectAndDollarQuotes(t *testing.T) {
	sqlText := `CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $body$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$body$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload JSONB,
  created_at TIMESTAMPTZ
);
`
	if got := DetectDialect("SELECT $1::bigint;", "inline.sql"); got != DialectPostgreSQL {
		t.Fatalf(":: 强转应识别为 PostgreSQL，实际 %s", got)
	}
	if got := DetectDialect(sqlText, "migrations/postgres/V1__init.sql"); got != DialectPostgreSQL {
		t.Fatalf("路径方言识别失败，实际 %s", got)
	}
	stmts := splitStatementsDialect(sqlText, DialectPostgreSQL)
	if len(stmts) != 2 {
		t.Fatalf("美元引号内的分号不应切分语句，期望 2 条，实际 %d: %#v", len(stmts), stmts)
	}
	toks := tokenizeDialect(`SELECT $$a;b$$, $tag$c;d$tag$, $1;`, DialectPostgreSQL)
	strs, vars := 0, 0
	for _, tok := range toks {
		if tok.Kind == "str" {
			strs++
		}
		if tok.Kind == "var" && tok.Text == "$1" {
			vars++
		}
	}
	if strs != 2 || vars != 1 {
		t.Fatalf("美元引号/$n 占位符解析失败: %#v", toks)
	}
	snippet := stripLiterals(sqlText)
	if strings.Contains(snippet, "NEW.updated_at") {
		t.Fatalf("报告片段不应泄露美元引号函数体: %s", snippet)
	}
}

func TestPostgresRules081To087(t *testing.T) {
	cases := []struct {
		name string
		sql  string
		rule string
	}{
		{"index without concurrently", "CREATE INDEX idx_users_email ON users (email);", "SQL081"},
		{"alter column type", "ALTER TABLE users ALTER COLUMN email TYPE varchar(320);", "SQL082"},
		{"set not null", "ALTER TABLE users ALTER COLUMN email SET NOT NULL;", "SQL083"},
		{"bigserial", "CREATE TABLE users (id BIGSERIAL PRIMARY KEY, email TEXT);", "SQL084"},
		{"json not jsonb", "CREATE TABLE events (id BIGINT PRIMARY KEY, payload JSON);", "SQL085"},
		{"timestamp without time zone", "CREATE TABLE events (id BIGINT PRIMARY KEY, created_at TIMESTAMP(3) WITHOUT TIME ZONE);", "SQL086"},
		{"drop cascade", "DROP TABLE users CASCADE;", "SQL087"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			res := pgResult(t, c.sql, false)
			f := findRule(res, c.rule)
			if f == nil {
				t.Fatalf("期望命中 %s，实际 %v", c.rule, ruleIDs(res))
			}
			if f.Snippet == "" {
				t.Fatalf("%s 应带脱敏片段", c.rule)
			}
		})
	}
}

func TestPostgresConcurrentIndexIsAccepted(t *testing.T) {
	res := pgResult(t, "CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_users_email ON users (email);", false)
	if findRule(res, "SQL081") != nil {
		t.Fatalf("CONCURRENTLY 索引不应命中 SQL081: %v", ruleIDs(res))
	}
}

func TestPostgresRule080OptionalAndGuards(t *testing.T) {
	cfg := defaultConfig().Rules
	var kept []string
	for _, id := range cfg.Disabled {
		if id != "SQL080" {
			kept = append(kept, id)
		}
	}
	cfg.Disabled = kept

	unguarded := AnalyzeSQL("CREATE TABLE users (id BIGINT PRIMARY KEY);",
		"migrations/postgres/V1__users.sql", cfg,
		AnalyzeOptions{Migration: true, Dialect: DialectPostgreSQL, NoUseRequired: true})
	if findRule(unguarded, "SQL080") == nil {
		t.Fatalf("开启 SQL080 后应命中裸 CREATE TABLE，实际 %v", ruleIDs(unguarded))
	}
	if findRule(unguarded, "SQL012") != nil {
		t.Fatal("PostgreSQL 不应误用 MySQL 的 SQL012")
	}

	guarded := AnalyzeSQL("CREATE TABLE IF NOT EXISTS users (id BIGINT PRIMARY KEY);",
		"migrations/postgres/V2__users.sql", cfg,
		AnalyzeOptions{Migration: true, Dialect: DialectPostgreSQL, NoUseRequired: true})
	if findRule(guarded, "SQL080") != nil {
		t.Fatalf("IF NOT EXISTS 已守卫，不应命中 SQL080: %v", ruleIDs(guarded))
	}

	guardedDrop := AnalyzeSQL("ALTER TABLE users DROP COLUMN IF EXISTS legacy;",
		"migrations/postgres/V2b__users.sql", cfg,
		AnalyzeOptions{Migration: true, Dialect: DialectPostgreSQL, NoUseRequired: true})
	if findRule(guardedDrop, "SQL080") != nil {
		t.Fatalf("DROP COLUMN IF EXISTS 已守卫，不应命中 SQL080: %v", ruleIDs(guardedDrop))
	}

	mixed := AnalyzeSQL("CREATE TABLE IF NOT EXISTS users (id BIGINT PRIMARY KEY);\nDROP TABLE legacy;",
		"migrations/postgres/V3__cleanup.sql", cfg,
		AnalyzeOptions{Migration: true, Dialect: DialectPostgreSQL, NoUseRequired: true})
	if findRule(mixed, "SQL080") == nil {
		t.Fatal("同文件中的裸 DROP 仍应命中 SQL080，不能被前面的守卫掩盖")
	}
}

func TestPostgresDoublePrecisionAndTimezoneFalsePositives(t *testing.T) {
	res := pgResult(t, `CREATE TABLE metrics (
  id BIGINT PRIMARY KEY,
  ratio DOUBLE PRECISION,
  created_at TIMESTAMP WITH TIME ZONE,
  payload JSONB
);`, false)
	for _, id := range []string{"SQL032", "SQL085", "SQL086"} {
		if f := findRule(res, id); f != nil {
			t.Fatalf("不应误报 %s: %+v", id, f)
		}
	}
}
